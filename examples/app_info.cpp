/**
 * @brief PixelUI brand and build information screen.
 */
class AboutApp : public IApplication {
private:
    PixelUI& m_ui;

public:
    /**
     * @brief Constructor for AboutApp.
     * @param ui Reference to the PixelUI instance.
     */
    AboutApp(PixelUI& ui, void* parameter) : m_ui(ui) {
        (void)parameter;
        setEnterTransitionEnabled(true);
    }
    ~AboutApp() = default;

    void draw() override {
        Canvas& display = m_ui.getCanvas();
        display.setFontDirection(0);
        display.setDrawColor(1);

        display.drawXBMP(5, 7, 28, 38, pixelui_logo_bits);

        display.setFont(u8g2_font_ncenB14_tr);
        display.drawStr(42, 20, "PixelUI");

        display.setFont(PIXELUI_FONT_TINY);
        display.drawStr(43, 31, "EMBEDDED UI SYSTEM");

        display.drawHLine(42, 37, 80);

        display.setFont(PIXELUI_FONT_SMALL);
        display.drawStr(43, 50, "VERSION beta 0.3.1");

        display.setFont(PIXELUI_FONT_TINY);
        display.drawStr(43, 61, "BSD-2  /  L. LINK");
    }

    /**
     * @brief Handles input events.
     * @param event The input event received.
     * @return true if the event was consumed, false otherwise.
     */
    bool handleInput(InputEvent event) override {
        if (event == InputEvent::BACK) {
            requestExit();
            return true;
        }
        return false;
    }

};

AppItem about_app = AppItem::make<AboutApp>("App Info", image_info_bits);
